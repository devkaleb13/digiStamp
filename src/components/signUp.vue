<script setup>
import { reactive, ref, computed } from 'vue'

const BRAND = 'DigiStamp'
const MAIL_DOMAIN = 'digistamp.app' // change to the domain you own

// true  = pretend the registration worked (no backend needed)
// false = send it to the real Laravel API
const USE_DEMO = true
const API = import.meta.env.VITE_API_URL || '/api'

const institutionTypes = [
  'Hospital or clinic',
  'University or college',
  'Government department',
  'Private company',
  'Other organisation',
]

// ---------- State ----------
const accountType = ref('institution') // 'institution' | 'individual'
const isInstitution = computed(() => accountType.value === 'institution')

const formRef = ref(null)
const form = reactive({
  institution: '',
  type: null,
  name: '',
  phone: '',
  email: '',
  password: '',
  confirm: '',
  agree: false,
})
const showPassword = ref(false)
const loading = ref(false)
const errorMessage = ref('')
const done = ref(false)
const loginEmail = ref('') // the email DigiStamp issues to the new account holder
const copied = ref(false)

// ---------- Validation rules ----------
const rules = {
  required: (v) => !!String(v ?? '').trim() || 'This field is required.',
  phone: (v) => /^(\+?254|0)\d{9}$/.test(String(v).replace(/\s/g, '')) || 'Enter a valid mobile number, e.g. 0712 345 678.',
  email: (v) => /^\S+@\S+\.\S+$/.test(String(v).trim()) || 'Enter a valid email address.',
  password: (v) =>
    (String(v).length >= 10 && /[A-Za-z]/.test(v) && /\d/.test(v)) ||
    'Use at least 10 characters, with letters and numbers.',
  confirm: (v) => v === form.password || 'The passwords do not match.',
  agree: (v) => !!v || 'You must confirm this to continue.',
}

// ---------- Password strength ----------
const strength = computed(() => {
  const p = form.password
  let score = 0
  if (p.length >= 10) score++
  if (/[a-z]/.test(p) && /[A-Z]/.test(p)) score++
  if (/\d/.test(p)) score++
  if (/[^A-Za-z0-9]/.test(p)) score++
  if (!p) return { value: 0, color: 'grey', label: '' }
  const table = [
    { value: 25, color: 'error', label: 'Weak' },
    { value: 50, color: 'warning', label: 'Fair' },
    { value: 75, color: 'info', label: 'Good' },
    { value: 100, color: 'success', label: 'Strong' },
  ]
  return table[Math.max(score - 1, 0)]
})

// Demo only: the real address is generated by the server, which guarantees it is unique
function demoLoginEmail() {
  const clean = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '.').replace(/^\.+|\.+$/g, '')
  const person = clean(form.name) || 'user'
  const place = isInstitution.value
    ? clean(form.institution).replace(/\./g, '').slice(0, 14) || 'institution'
    : 'personal'
  return `${person}@${place}.${MAIL_DOMAIN}`
}

async function copyLoginEmail() {
  try {
    await navigator.clipboard.writeText(loginEmail.value)
    copied.value = true
    setTimeout(() => (copied.value = false), 2000)
  } catch {
    /* clipboard not available: the address is still shown on screen */
  }
}

// ---------- Submit ----------
async function submit() {
  errorMessage.value = ''
  const { valid } = await formRef.value.validate()
  if (!valid) return

  loading.value = true
  try {
    if (USE_DEMO) {
      await new Promise((r) => setTimeout(r, 900))
      loginEmail.value = demoLoginEmail()
    } else {
      let res
      try {
        res = await fetch(`${API}/register`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
          body: JSON.stringify({
            account_type: accountType.value, // 'institution' or 'individual'
            institution: isInstitution.value ? form.institution.trim() : null,
            institution_type: isInstitution.value ? form.type : null,
            name: form.name.trim(),
            phone: form.phone,
            contact_email: form.email.trim(),
            password: form.password,
            password_confirmation: form.confirm,
          }),
        })
      } catch {
        throw new Error('Could not reach the server. Check your connection.')
      }
      if (!res.ok) {
        const data = await res.json().catch(() => ({}))
        throw new Error(data.message || 'Registration failed. Please try again.')
      }
      const data = await res.json().catch(() => ({}))
      loginEmail.value = data.login_email || '' // issued by the server
    }
    done.value = true
  } catch (e) {
    errorMessage.value = e.message
  } finally {
    loading.value = false
  }
}
</script>

<template>
  <div class="bg-section d-flex align-center justify-center py-12 px-4" style="min-height: calc(100vh - 68px)">
    <v-card
      max-width="600"
      width="100%"
      rounded="lg"
      elevation="6"
      class="pa-6 pa-sm-8"
      style="border-top: 4px solid #d4af37"
    >
      <!-- ============ SUCCESS ============ -->
      <template v-if="done">
        <div class="text-center">
          <v-avatar color="success" size="64" class="mb-4">
            <v-icon icon="mdi-check-bold" color="white" size="34" />
          </v-avatar>
          <h1 class="serif text-h5 text-primary">Registration received</h1>
          <p class="text-body-1 text-medium-emphasis mt-3">
            Thank you, {{ form.name }}. We sent a confirmation to <strong>{{ form.email }}</strong>.
          </p>
        </div>

        <v-sheet v-if="loginEmail" rounded class="pa-4 mt-6 border" style="border-color: #d4af37 !important">
          <p class="text-overline text-medium-emphasis">Your {{ BRAND }} login email</p>
          <div class="d-flex align-center ga-2">
            <strong class="text-primary text-body-1" style="word-break: break-all">{{ loginEmail }}</strong>
            <v-btn
              :icon="copied ? 'mdi-check' : 'mdi-content-copy'"
              :color="copied ? 'success' : 'primary'"
              variant="text"
              size="small"
              aria-label="Copy login email"
              @click="copyLoginEmail"
            />
          </div>
          <p class="text-caption text-medium-emphasis mt-1">
            Use this address, not your contact email, to sign in. It is personal to you, so do not share it.
          </p>
        </v-sheet>

        <v-sheet color="section" rounded class="pa-4 mt-6 text-body-2">
          <strong>What happens next</strong>
          <ol v-if="isInstitution" class="ml-4 mt-2">
            <li>Confirm your contact email using the link we sent. We also send your login email there.</li>
            <li>Your institution is checked and activated.</li>
            <li>You sign in with your {{ BRAND }} login email and add your authorised officers. Each officer gets their own unique login email.</li>
            <li>Each officer registers their own computer before using the stamp.</li>
          </ol>
          <ol v-else class="ml-4 mt-2">
            <li>Confirm your contact email using the link we sent. We also send your login email there.</li>
            <li>Open the activation link on the computer you will use, and register that computer.</li>
            <li>Sign in with your {{ BRAND }} login email, your password and the code sent to your phone.</li>
            <li>Upload a document and apply your personal stamp. Every action is recorded in your own audit history.</li>
          </ol>
        </v-sheet>

        <v-btn block size="large" color="primary" variant="flat" to="/" class="mt-6">Back to the homepage</v-btn>
      </template>

      <!-- ============ FORM ============ -->
      <template v-else>
        <div class="text-center mb-6">
          <v-avatar color="primary" size="56" class="mb-3">
            <v-icon :icon="isInstitution ? 'mdi-domain-plus' : 'mdi-account-plus-outline'" color="secondary" size="30" />
          </v-avatar>
          <h1 class="serif text-h5 text-primary">
            {{ isInstitution ? 'Register your institution' : 'Create your personal account' }}
          </h1>
        </div>

        <!-- Account type -->
        <v-btn-toggle
          v-model="accountType"
          mandatory
          divided
          color="primary"
          variant="outlined"
          class="d-flex mb-4"
          style="height: auto"
          aria-label="Account type"
        >
          <v-btn value="institution" class="flex-grow-1 py-3" prepend-icon="mdi-domain">Institution</v-btn>
          <v-btn value="individual" class="flex-grow-1 py-3" prepend-icon="mdi-account-outline">Individual</v-btn>
        </v-btn-toggle>

        <p v-if="isInstitution" class="text-body-2 text-medium-emphasis mb-4">
          For the person who administers the institution's stamp. {{ BRAND }} issues you a unique login email after
          you register. Officers do not register here, you add them once your institution is activated.
        </p>
        <v-alert v-else type="info" variant="tonal" density="compact" class="mb-4 text-body-2">
          Personal accounts are for your own private documents. You are the only person who approves and stamps, so
          there are no departments or approval steps. Your stamp carries your name, not an institution's, and the
          people you send documents to decide whether to accept it.
        </v-alert>

        <v-alert v-if="USE_DEMO" type="info" variant="tonal" density="compact" class="mb-4 text-caption">
          Demo mode: nothing is saved. Fill in the form to see the confirmation screen.
        </v-alert>

        <v-alert v-if="errorMessage" type="error" variant="tonal" density="compact" class="mb-4" role="alert">
          {{ errorMessage }}
        </v-alert>

        <v-form ref="formRef" validate-on="blur lazy" @submit.prevent="submit">
          <template v-if="isInstitution">
            <p class="text-overline text-medium-emphasis mb-2">The institution</p>
            <v-row dense>
              <v-col cols="12" sm="7">
                <v-text-field
                  v-model="form.institution"
                  label="Institution name"
                  variant="outlined"
                  prepend-inner-icon="mdi-domain"
                  autocomplete="organization"
                  :rules="[rules.required]"
                />
              </v-col>
              <v-col cols="12" sm="5">
                <v-select
                  v-model="form.type"
                  :items="institutionTypes"
                  label="Type"
                  variant="outlined"
                  :rules="[rules.required]"
                />
              </v-col>
            </v-row>
          </template>

          <p class="text-overline text-medium-emphasis mb-2 mt-1">
            {{ isInstitution ? 'The administrator' : 'About you' }}
          </p>
          <v-text-field
            v-model="form.name"
            label="Full name"
            :hint="isInstitution ? '' : 'This name appears on your stamp'"
            :persistent-hint="!isInstitution"
            variant="outlined"
            prepend-inner-icon="mdi-account-outline"
            autocomplete="name"
            :rules="[rules.required]"
            class="mb-1"
          />
          <v-row dense>
            <v-col cols="12" sm="6">
              <v-text-field
                v-model="form.phone"
                label="Mobile number"
                hint="Codes are sent here"
                variant="outlined"
                prepend-inner-icon="mdi-cellphone"
                placeholder="0712 345 678"
                autocomplete="tel"
                :rules="[rules.phone]"
              />
            </v-col>
            <v-col cols="12" sm="6">
              <v-text-field
                v-model="form.email"
                label="Contact email"
                hint="For confirmation and password recovery"
                type="email"
                variant="outlined"
                prepend-inner-icon="mdi-email-outline"
                autocomplete="email"
                :rules="[rules.email]"
              />
            </v-col>
          </v-row>

          <v-text-field
            v-model="form.password"
            label="Password"
            :type="showPassword ? 'text' : 'password'"
            variant="outlined"
            prepend-inner-icon="mdi-lock-outline"
            :append-inner-icon="showPassword ? 'mdi-eye-off-outline' : 'mdi-eye-outline'"
            autocomplete="new-password"
            :rules="[rules.password]"
            @click:append-inner="showPassword = !showPassword"
          />
          <div v-if="form.password" class="mt-n3 mb-3">
            <v-progress-linear :model-value="strength.value" :color="strength.color" height="4" rounded />
            <span class="text-caption text-medium-emphasis">Password strength: {{ strength.label }}</span>
          </div>

          <v-text-field
            v-model="form.confirm"
            label="Confirm password"
            :type="showPassword ? 'text' : 'password'"
            variant="outlined"
            prepend-inner-icon="mdi-lock-check-outline"
            autocomplete="new-password"
            :rules="[rules.confirm]"
          />

          <v-checkbox
            v-model="form.agree"
            color="primary"
            density="compact"
            :rules="[rules.agree]"
            :label="
              isInstitution
                ? 'I am authorised to register this institution and I accept the terms of use.'
                : 'I confirm these details are mine and I accept the terms of use.'
            "
          />

          <v-btn type="submit" block size="large" color="secondary" variant="flat" :loading="loading" class="mt-2">
            {{ isInstitution ? 'Register institution' : 'Create personal account' }}
          </v-btn>
        </v-form>

        <p class="text-center text-body-2 text-medium-emphasis mt-5">
          Already registered?
          <router-link to="/login" class="text-primary font-weight-bold">Sign in</router-link>
        </p>
      </template>
    </v-card>
  </div>
</template>